#!/usr/bin/env python3
"""Turns the icons of the concept page (SVG paths in mockups/ux-concept.html) into line strips for the device:
main/icons.h.  The device strokes them with round ends, like the concept does.  Usage: python3 tools/make_icons.py"""
import os, re, math
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..", "..", "..")
src = open(os.path.join(ROOT, "mockups", "ux-concept.html")).read()
body = src[src.index("function ico("):]; body = body[body.index("const p={") + 9:body.index("}[n];")]
icons = re.findall(r"(\w+):'([^']*)'", body)

def arc_pts(x0, y0, rx, ry, large, sweep, x1, y1, n=10):
    if (x0, y0) == (x1, y1): return []
    dx, dy = (x0 - x1) / 2, (y0 - y1) / 2; lam = dx * dx / (rx * rx) + dy * dy / (ry * ry)
    if lam > 1: s = math.sqrt(lam); rx *= s; ry *= s
    num = max(0.0, rx * rx * ry * ry - rx * rx * dy * dy - ry * ry * dx * dx); den = rx * rx * dy * dy + ry * ry * dx * dx
    co = (1 if large != sweep else -1) * math.sqrt(num / den) if den else 0
    cxp, cyp = co * rx * dy / ry, -co * ry * dx / rx; cx, cy = cxp + (x0 + x1) / 2, cyp + (y0 + y1) / 2
    a0 = math.atan2((dy - cyp) / ry, (dx - cxp) / rx); a1 = math.atan2((-dy - cyp) / ry, (-dx - cxp) / rx); da = a1 - a0
    if sweep and da < 0: da += 2 * math.pi
    if not sweep and da > 0: da -= 2 * math.pi
    k = max(3, int(abs(da) / (math.pi / 8)) + 1)
    return [(cx + rx * math.cos(a0 + da * i / k), cy + ry * math.sin(a0 + da * i / k)) for i in range(1, k + 1)]

def path(d):
    toks = re.findall(r"[MLHVCSAZ]|-?\d*\.?\d+", d); i = 0; polys = []; cur = []; x = y = 0; sx = sy = 0; cmd = None; lc = None
    def num():
        nonlocal i; v = float(toks[i]); i += 1; return v
    while i < len(toks):
        if toks[i].isalpha(): cmd = toks[i]; i += 1
        if cmd == "M":
            if cur: polys.append(cur)
            x, y = num(), num(); sx, sy = x, y; cur = [(x, y)]; cmd = "L"; lc = None
        elif cmd == "L": x, y = num(), num(); cur.append((x, y)); lc = None
        elif cmd == "H": x = num(); cur.append((x, y)); lc = None
        elif cmd == "V": y = num(); cur.append((x, y)); lc = None
        elif cmd in "CS":
            if cmd == "C": x1, y1 = num(), num()
            else: x1, y1 = (2 * x - lc[0], 2 * y - lc[1]) if lc else (x, y)
            x2, y2, x3, y3 = num(), num(), num(), num()
            for k in range(1, 8):
                t = k / 7; u = 1 - t
                cur.append((u**3 * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t**3 * x3, u**3 * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t**3 * y3))
            lc = (x2, y2); x, y = x3, y3
        elif cmd == "A":
            rx, ry, _, large, sweep, x1, y1 = num(), num(), num(), int(num()), int(num()), num(), num()
            cur += arc_pts(x, y, rx, ry, large, sweep, x1, y1); x, y = x1, y1; lc = None
        elif cmd == "Z": cur.append((sx, sy)); x, y = sx, sy; lc = None
    if cur: polys.append(cur)
    return polys

def shapes(svg):
    out = []
    for tag, attrs in re.findall(r"<(rect|circle|path)([^>]*)/>", svg):
        a = dict(re.findall(r'(\w+)="([^"]*)"', attrs))
        if tag == "path": out += path(a["d"])
        elif tag == "circle":
            cx, cy, r = float(a.get("cx", 0)), float(a.get("cy", 0)), float(a["r"]); n = 14
            out.append([(cx + r * math.cos(2 * math.pi * k / n), cy + r * math.sin(2 * math.pi * k / n)) for k in range(n + 1)])
        else:
            x, y, w, h, r = (float(a[k]) for k in ("x", "y", "width", "height", "rx"))
            out += path(f"M{x+r} {y}H{x+w-r}A{r} {r} 0 0 1 {x+w} {y+r}V{y+h-r}A{r} {r} 0 0 1 {x+w-r} {y+h}H{x+r}A{r} {r} 0 0 1 {x} {y+h-r}V{y+r}A{r} {r} 0 0 1 {x+r} {y}Z")
    return out

o = ["/* Generated by tools/make_icons.py from the concept page: do not edit. Line strips, 1 unit = 1 px at scale 1. */", "#pragma once", "#include <stdint.h>",
     "typedef struct { uint8_t n; const float *xy; } ico_strip_t;", "typedef struct { uint8_t n; const ico_strip_t *s; } ico_t;",
     "enum { " + ", ".join("ICO_" + n.upper() for n, _ in icons) + ", ICO_COUNT };"]
for n, svg in icons:
    ss = shapes(svg)
    for k, p in enumerate(ss): o.append(f"static const float ico_{n}_{k}[] = {{" + ", ".join(f"{x:.2f}f, {y:.2f}f" for x, y in p) + "};")
    o.append(f"static const ico_strip_t ico_{n}_s[] = {{" + ", ".join(f"{{{len(p)}, ico_{n}_{k}}}" for k, p in enumerate(ss)) + "};")
o.append("static const ico_t ICONS[ICO_COUNT] = {" + ", ".join(f"{{{len(shapes(svg))}, ico_{n}_s}}" for n, svg in icons) + "};")
open(os.path.join(HERE, "..", "main", "icons.h"), "w").write("\n".join(o) + "\n")
print(len(icons), "icons:", " ".join(f"{n}={sum(len(p) for p in shapes(svg))}" for n, svg in icons))
