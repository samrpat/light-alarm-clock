#!/usr/bin/env python3
"""Builds the device's bitmap fonts from Inter (SIL Open Font Licence, docs/licenses/Inter-OFL.txt).
Needs only Python 3 and Pillow, and the TTFs kept in tools/fonts-src: no download, no other tool
(LONGEVITY.md section 5).  Output: main/fonts/inter_<name>.c in LVGL's 4-bit font format, plus fonts.h.
Usage: python3 tools/make_fonts.py"""
import os, sys
from PIL import Image, ImageDraw, ImageFont, features

HERE = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(HERE, "fonts-src"); OUT = os.path.join(HERE, "..", "main", "fonts")
TEXT = [chr(c) for c in range(0x20, 0x7F)] + ["±", "·", "’", "−"]
D = "0123456789"
FONTS = [  # name, weight, size, characters
    ("r26", "Regular", 26, TEXT), ("m26", "Medium", 26, TEXT), ("r28", "Regular", 28, TEXT), ("m28", "Medium", 28, TEXT), ("l28", "Light", 28, TEXT),
    ("m30", "Medium", 30, TEXT), ("r34", "Regular", 34, TEXT), ("m34", "Medium", 34, TEXT),
    ("r38", "Regular", 38, D), ("m38", "Medium", 38, D), ("l38", "Light", 38, TEXT),
    ("m40", "Medium", 40, TEXT), ("m44", "Medium", 44, TEXT), ("l44", "Light", 44, D),
    ("l46", "Light", 46, TEXT), ("l56", "Light", 56, D + ":APM "), ("l66", "Light", 66, ":"), ("l72", "Light", 72, D + "%"),
    ("l76", "Light", 76, D + "%Of"), ("l80", "Light", 80, D), ("l96", "Light", 96, D + ":"), ("l110", "Light", 110, D), ("l124", "Light", 124, D + ":"),
]
RAQM = features.check("raqm")

def build(name, weight, size, chars):
    chars = sorted(set(chars), key=ord)
    kw = {"layout_engine": ImageFont.Layout.RAQM} if RAQM else {}
    font = ImageFont.truetype(os.path.join(SRC, f"Inter-{weight}.ttf"), size, **kw)
    ascent, descent = font.getmetrics(); pad = size
    bitmap = bytearray(); dsc = []
    for ch in chars:
        img = Image.new("L", (size * 3, size * 3), 0)
        ImageDraw.Draw(img).text((pad, pad + size), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox(); adv = round(font.getlength(ch) * 16)
        if not box: dsc.append((len(bitmap), adv, 0, 0, 0, 0)); continue
        l, t, r, b = box; w, h = r - l, b - t; px = img.crop(box).tobytes()
        start = len(bitmap); acc = 0; n = 0
        for v in px:                                       # 4 bits a pixel, packed with no row padding
            acc = (acc << 4) | ((v + 8) // 17); n += 1
            if n == 2: bitmap.append(acc); acc = 0; n = 0
        if n: bitmap.append(acc << 4)
        dsc.append((start, adv, w, h, l - pad, (pad + size) - b))
    cap = font.getbbox("H", anchor="ls") if "H" in chars else font.getbbox("0", anchor="ls")
    # character map: one dense run from the first character if possible, the rest as a sorted list
    codes = [ord(c) for c in chars]; run = 1
    while run < len(codes) and codes[run] == codes[0] + run: run += 1
    rest = codes[run:]
    kern = []
    if RAQM and len(chars) > 20:                           # kerning pairs (Inter keeps its kerning in GPOS)
        single = {c: font.getlength(c) for c in chars}
        for i, a in enumerate(chars):
            for j, b in enumerate(chars):
                k = round((font.getlength(a + b) - single[a] - single[b]) * 16)
                if k and -128 <= k <= 127: kern.append((j + 1, i + 1, k))        # sorted by right glyph, then left
        kern.sort()
    o = [f"/* Inter {weight} {size} px, {len(chars)} glyphs. Generated by tools/make_fonts.py: do not edit. */", '#include "lvgl.h"', "",
         "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {"]
    for i in range(0, len(bitmap), 20): o.append("    " + ", ".join(f"0x{v:02x}" for v in bitmap[i:i + 20]) + ",")
    o += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {", "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"]
    for (bi, adv, w, h, ox, oy) in dsc: o.append(f"    {{.bitmap_index = {bi}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}},")
    o += ["};", ""]
    if rest: o += ["static const uint16_t unicode_list_1[] = {" + ", ".join(str(c - rest[0]) for c in rest) + "};", ""]
    o += ["static const lv_font_fmt_txt_cmap_t cmaps[] = {",
          f"    {{.range_start = {codes[0]}, .range_length = {run}, .glyph_id_start = 1, .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},"]
    if rest: o.append(f"    {{.range_start = {rest[0]}, .range_length = {rest[-1] - rest[0] + 1}, .glyph_id_start = {run + 1}, .unicode_list = unicode_list_1, .glyph_id_ofs_list = NULL, .list_length = {len(rest)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},")
    o += ["};", ""]
    if kern:
        o += ["static const uint8_t kern_pair_glyph_ids[] = {"] + ["    " + ", ".join(f"{l}, {r}" for (r, l, k) in kern[i:i + 12]) + "," for i in range(0, len(kern), 12)] + ["};",
              "static const int8_t kern_pair_values[] = {"] + ["    " + ", ".join(str(k) for (_, _, k) in kern[i:i + 24]) + "," for i in range(0, len(kern), 24)] + ["};",
              f"static const lv_font_fmt_txt_kern_pair_t kern_pairs = {{.glyph_ids = kern_pair_glyph_ids, .values = kern_pair_values, .pair_cnt = {len(kern)}, .glyph_ids_size = 0}};", ""]
    o += ["static const lv_font_fmt_txt_dsc_t font_dsc = {", "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,",
          f"    .kern_dsc = {'&kern_pairs' if kern else 'NULL'}, .kern_scale = {16 if kern else 0}, .cmap_num = {2 if rest else 1}, .bpp = 4, .kern_classes = 0, .bitmap_format = 0,", "};", "",
          f"const lv_font_t inter_{name} = {{", "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
          f"    .line_height = {ascent + descent}, .base_line = {descent}, .cap_height = {-cap[1]}, .x_height = {round(size * 0.546)},",
          "    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -2, .underline_thickness = 1, .static_bitmap = 1, .dsc = &font_dsc, .fallback = NULL, .user_data = NULL,", "};", ""]
    open(os.path.join(OUT, f"inter_{name}.c"), "w").write("\n".join(o))
    return len(bitmap), len(kern), -cap[1]

os.makedirs(OUT, exist_ok=True); total = 0; hdr = ["/* Generated by tools/make_fonts.py */", "#pragma once", '#include "lvgl.h"']
for f in FONTS:
    n, k, cap = build(*f); total += n + 3 * k; hdr.append(f"extern const lv_font_t inter_{f[0]};"); print(f"inter_{f[0]:5s} {f[1]:8s} {f[2]:4d}px  {n/1024:6.1f} KB  kern pairs {k:4d}  cap {cap}")
open(os.path.join(OUT, "fonts.h"), "w").write("\n".join(hdr) + "\n")
print(f"total about {total/1024:.0f} KB; kerning {'on' if RAQM else 'OFF (Pillow has no raqm)'}")
