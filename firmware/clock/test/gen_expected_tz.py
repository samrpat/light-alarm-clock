#!/usr/bin/env python3
"""Independent check data for the DST tests (T-28). Uses the system time-zone database through Python's
zoneinfo, which is a different implementation from the firmware's rule formulas. Writes expected_tz.inc:
every UTC instant at which each region's offset changes, 2026..2099."""
import datetime as dt, sys
from zoneinfo import ZoneInfo
regions = [("US Eastern","America/New_York"),("US Central","America/Chicago"),("US Mountain","America/Denver"),
           ("US Pacific","America/Los_Angeles"),("US Alaska","America/Anchorage"),("US Hawaii","Pacific/Honolulu"),
           ("UK","Europe/London"),("Central Europe","Europe/Berlin"),("Manual","UTC"),("Sydney","Australia/Sydney")]
out = ["/* generated by gen_expected_tz.py: do not edit */"]
utc = dt.timezone.utc
start = dt.datetime(2026,1,1,tzinfo=utc); end = dt.datetime(2100,1,1,tzinfo=utc)
for i,(n,z) in enumerate(regions):
    zi = ZoneInfo(z); rows=[]; t=start; prev=t.astimezone(zi).utcoffset()
    while t<end:
        nt=t+dt.timedelta(hours=1); o=nt.astimezone(zi).utcoffset()
        if o!=prev: rows.append((int(nt.timestamp()), int(o.total_seconds()))); prev=o
        t=nt
    out.append(f"static const struct {{int64_t utc; int32_t off;}} EXP_{i}[] = {{")
    out += [f"  {{{u}LL,{o}}}," for u,o in rows]
    out.append("  {0,0}};")
open("expected_tz.inc","w").write("\n".join(out)+"\n"); print("ok", sys.version.split()[0])
